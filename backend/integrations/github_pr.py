from __future__ import annotations


def build_recovery_pr_body(
    incident_id: str,
    root_cause: dict,
    risk: dict,
    test_results: dict,
    patch_diff: str,
    evidence: dict | None = None,
) -> str:
    root_cause_summary = str(
        root_cause.get(
            "summary",
            "Automated root-cause analysis completed.",
        )
    )

    sources_section = "### Sources\n\nNo external evidence found."
    if evidence:
        sources = evidence.get("sources") or []
        confidence = str(evidence.get("confidence", "none")).lower()
        if sources and confidence != "none":
            items = []
            for s in sources:
                sid = s.get("id", 1)
                title = s.get("title") or f"Source {sid}"
                url = s.get("url") or "#"
                snippet = (s.get("snippet") or s.get("extracted") or "").strip().replace("\n", " ")
                summary = snippet[:140] + "..." if len(snippet) > 140 else (snippet or "Reference fix pattern")
                support = s.get("support") or "Supports root-cause diagnosis and recovery patch"
                items.append(f"- [{sid}] [{title}]({url}) - {summary} *(Supports: {support})*")
            sources_section = "### Sources\n\n" + "\n".join(items)

    risk_score = float(
        risk.get(
            "score",
            1.0,
        )
    )

    decision = str(
        risk.get(
            "decision",
            "BLOCK",
        )
    )

    breakdown = risk.get(
        "breakdown",
        [],
    )

    if isinstance(breakdown, list):
        breakdown_text = "\n".join(
            f"- {item}"
            for item in breakdown
        )
    else:
        breakdown_text = f"- {breakdown}"

    exit_code = test_results.get(
        "exit_code",
        -1,
    )

    return f"""## Autonomous Recovery Engine

### Incident

`{incident_id}`

### Root Cause

{root_cause_summary}

{sources_section}

### Explainable Risk

**Score:** `{risk_score:.4f}`

**Decision:** `{decision}`

#### Risk Breakdown

{breakdown_text}

### Verification (RED -> GREEN)

<details>
<summary>Pre-Patch RED (Failing)</summary>

```
{test_results.get("before_test", {}).get("stdout", "No pre-patch output")}
```
</details>

<details>
<summary>Post-Patch GREEN (Passing)</summary>

```
{test_results.get("after_test", {}).get("stdout", "No post-patch output")}
```
</details>

### Generated Patch
**Patch Hash:** `{hash(patch_diff)}`

```diff
{patch_diff}
```

### Recovery Policy

This pull request was generated by the Autonomous Recovery Engine
after automated patch validation and sandbox verification.

Human review remains required before merging.
"""
