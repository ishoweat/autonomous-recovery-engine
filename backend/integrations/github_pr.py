from __future__ import annotations


def build_recovery_pr_body(
    incident_id: str,
    root_cause: dict,
    risk: dict,
    test_results: dict,
    patch_diff: str,
) -> str:
    root_cause_summary = str(
        root_cause.get(
            "summary",
            "Automated root-cause analysis completed.",
        )
    )

    risk_score = float(
        risk.get(
            "score",
            1.0,
        )
    )

    decision = str(
        risk.get(
            "decision",
            "BLOCK",
        )
    )

    breakdown = risk.get(
        "breakdown",
        [],
    )

    if isinstance(breakdown, list):
        breakdown_text = "\n".join(
            f"- {item}"
            for item in breakdown
        )
    else:
        breakdown_text = f"- {breakdown}"

    exit_code = test_results.get(
        "exit_code",
        -1,
    )

    return f"""## Autonomous Recovery Engine

### Incident

`{incident_id}`

### Root Cause

{root_cause_summary}

### Explainable Risk

**Score:** `{risk_score:.4f}`

**Decision:** `{decision}`

#### Risk Breakdown

{breakdown_text}

### Verification

- Test exit code: `{exit_code}`
- Tests passed: `{test_results.get("tests_passed", False)}`
- Timed out: `{test_results.get("timed_out", False)}`

### Generated Patch

```diff
{patch_diff}
```

### Recovery Policy

This pull request was generated by the Autonomous Recovery Engine
after automated patch validation and sandbox verification.

Human review remains required before merging.
"""
